-- This is the canonical, from-scratch schema for a brand-new installation -
-- generated via `pg_dump --schema-only --no-owner --no-privileges` against
-- a database that already had every file in db/migrations/ applied.
--
-- It exists because db/migrations/ is NOT a complete history: the earliest
-- tracked migration (001) already ALTERs tables like `submissions` that no
-- migration ever CREATEs - they were set up once, untracked, before this
-- migrations/ folder started. That's fine for evolving an existing
-- database, but it means replaying 001-021 against a truly empty database
-- does not work. This file is the fix: run it once, instead of the
-- migrations, to stand up a fresh database (see db/Dockerfile, which does
-- exactly that for the Docker image). Verified by restoring it into a
-- throwaway empty database and confirming it matches the live schema
-- exactly (28 tables, 30 foreign keys) before this comment was written.
--
-- db/migrations/ is kept as-is: it's still the right place for whoever
-- maintains an already-running installation to apply incremental changes
-- going forward. A fresh install only ever needs this one file.

