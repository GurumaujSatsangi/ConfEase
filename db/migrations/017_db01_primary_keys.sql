-- DB-01 (security-audit/COMPLETE_FINDINGS_REGISTER.md), part 1 of 2: every
-- table should have a primary key. Live introspection at the time this was
-- written found 8 tables with none - more than the original audit's count
-- of 5, which missed certificates, meta_reviewer_decision, registration,
-- and role_certificates (conference_roles, one of the original 5, already
-- got a surrogate `id` PK in migration 013 for an unrelated indexing fix,
-- so it's not repeated here).
--
-- Four of these (certificates, meta_reviewer_decision, registration,
-- role_certificates) already have a UNIQUE constraint/index on exactly the
-- column(s) that should be the primary key - verified live that none of
-- them currently hold duplicate or NULL values on those columns, so
-- promoting the existing unique index directly is safe. revised_submissions
-- and poster_presentation_scores get a new surrogate id instead:
-- revised_submissions genuinely has multiple rows per submission_id (a
-- revision history - confirmed live: one submission_id with 2 rows), so
-- submission_id cannot be its key; poster_presentation_scores has no
-- INSERT anywhere in the current codebase (only DELETE, as cleanup inside
-- the conference/submission cascade-delete paths), so its real key shape
-- is undetermined - a surrogate id satisfies "every table has a PK"
-- without guessing at unverified business rules. announcements has no
-- id-like column at all, so it gets a brand new one. activation_requests
-- already has an unused `id bigint` column (no default, nothing in
-- api/index.js ever reads or writes it - every lookup there uses
-- activation_code instead) - given it exists and is currently always NULL,
-- it's turned into a real identity column rather than adding a second,
-- redundant id column.

-- Each of these four already has a UNIQUE constraint on exactly the
-- column(s) being promoted to the primary key - drop it first so the PK's
-- own (equivalent) unique index isn't just a redundant duplicate sitting
-- alongside it. ON CONFLICT clauses elsewhere in api/index.js specify
-- these column lists directly (not by constraint name), so they keep
-- matching the PK's index exactly the same way they matched the old one.
ALTER TABLE certificates DROP CONSTRAINT certificates_submission_id_key;
ALTER TABLE certificates ALTER COLUMN submission_id SET NOT NULL;
ALTER TABLE certificates ADD CONSTRAINT certificates_pkey PRIMARY KEY (submission_id);

ALTER TABLE meta_reviewer_decision DROP CONSTRAINT meta_reviewer_decision_submission_id_key;
ALTER TABLE meta_reviewer_decision ALTER COLUMN submission_id SET NOT NULL;
ALTER TABLE meta_reviewer_decision ADD CONSTRAINT meta_reviewer_decision_pkey PRIMARY KEY (submission_id);

ALTER TABLE registration DROP CONSTRAINT registration_submission_id_key;
ALTER TABLE registration ALTER COLUMN submission_id SET NOT NULL;
ALTER TABLE registration ADD CONSTRAINT registration_pkey PRIMARY KEY (submission_id);

ALTER TABLE role_certificates DROP CONSTRAINT role_certificates_conference_id_role_email_context_id_key;
ALTER TABLE role_certificates ADD CONSTRAINT role_certificates_pkey PRIMARY KEY (conference_id, role, email, context_id);

ALTER TABLE revised_submissions ADD COLUMN id bigserial;
ALTER TABLE revised_submissions ADD CONSTRAINT revised_submissions_pkey PRIMARY KEY (id);

ALTER TABLE poster_presentation_scores ADD COLUMN id bigserial;
ALTER TABLE poster_presentation_scores ADD CONSTRAINT poster_presentation_scores_pkey PRIMARY KEY (id);

ALTER TABLE announcements ADD COLUMN id bigserial;
ALTER TABLE announcements ADD CONSTRAINT announcements_pkey PRIMARY KEY (id);

ALTER TABLE activation_requests ALTER COLUMN id SET NOT NULL;
ALTER TABLE activation_requests ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE activation_requests ADD CONSTRAINT activation_requests_pkey PRIMARY KEY (id);
